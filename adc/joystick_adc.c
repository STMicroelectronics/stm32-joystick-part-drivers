/* Exported functions --------------------------------------------------------*/

/**
  * @brief This function initializes joystick instance by
  * linking the joystick instance with the adc interface
  * The ADC peripheral must be initialized beforehand.
  * Usually it is initialized by auto generated code from STM32CubeMX2 otherwise
  * it is up to the user to correctly initialize the ADC and relates peripheral.
  * @param pjoy_adc   : Pointer to the joystick ADC structure.
  * @param id         : Config ID, Each object has a unique ID representing the configuration ID.
  * @retval error status.
  * @note The parameter pointers must be allocated outside the part driver.
  */
joy_adc_status_t joy_adc_init(joy_adc_t *pjoy_adc, uint32_t id)
{
  /* Store Device id */
  pjoy_adc->id    = id;

  /* initialize hardware resource */
  if (joy_adc_io_init(pjoy_adc) == 0)
  {
    return JOY_ADC_OK;
  }
  else
  {
    return JOY_ADC_ERROR;
  }
}

/**
  * @brief This function returns the keys state of the joystick through adc,
  * conversions performed in single conversion with polling mode.
  * @param pjoy_adc   : Pointer to the joystick ADC structure.
  * @param pkey       : Pointer to the joystick key state.
  * @retval error status.
  * @note The parameter pointers must be allocated outside the part driver.
  * @note The key state is determined by comparing the input key value in the part object with the ADC value
  */
joy_adc_status_t joy_adc_get_state(joy_adc_t *pjoy_adc, joy_adc_key_t *pkey)
{
  int32_t adc_value;
  joy_adc_status_t joy_status = JOY_ADC_OK;

  /* Start new conversion process */
  if (HAL_ADC_REG_StartConv(pjoy_adc->phadc) == HAL_OK)
  {
    /* Wait for the end of conversion */
    if (HAL_ADC_REG_PollForConv(pjoy_adc->phadc, JOY_ADC_POLL_TIMEOUT) == HAL_OK)
    {
      /* Retrieve the ADC value from the regular channel */
      adc_value = HAL_ADC_REG_ReadConversionData(pjoy_adc->phadc);

      if ((adc_value >= pjoy_adc->key_up_min_val) && (adc_value <= pjoy_adc->key_up_max_val))
      {
        *pkey = JOY_ADC_KEY_UP;
      }
      else if ((adc_value >= pjoy_adc->key_right_min_val) && (adc_value <= pjoy_adc->key_right_max_val))
      {
        *pkey = JOY_ADC_KEY_RIGHT;
      }
      else if ((adc_value >= pjoy_adc->key_center_min_val) && (adc_value <= pjoy_adc->key_center_max_val))
      {
        *pkey = JOY_ADC_KEY_CENTER;
      }
      else if ((adc_value >= pjoy_adc->key_down_min_val) && (adc_value <= pjoy_adc->key_down_max_val))
      {
        *pkey = JOY_ADC_KEY_DOWN;
      }
      else if ((adc_value >= pjoy_adc->key_left_min_val) && (adc_value <= pjoy_adc->key_left_max_val))
      {
        *pkey = JOY_ADC_KEY_LEFT;
      }
      else
      {
        *pkey = JOY_ADC_KEY_NONE;
      }
    }
    else
    {
      joy_status = JOY_ADC_ERROR;
    }

    /* Stop last conversion */
    if (HAL_ADC_REG_StopConv(pjoy_adc->phadc) != HAL_OK)
    {
      joy_status = JOY_ADC_ERROR;
    }
  }
  else
  {
    joy_status = JOY_ADC_ERROR;
  }

  return joy_status;
}

